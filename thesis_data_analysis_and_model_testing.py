def classify_new_junction(new_features, model, scaler, cluster_names):
    """
    Classify a new junction based on its features

    Args:
        new_features (dict): Dictionary with junction features
        model: Trained classification model
        scaler: Fitted scaler
        cluster_names (dict): Mapping from cluster IDs to names

    Returns:
        dict: Classification results
    """
    # Convert input to DataFrame
    input_df = pd.DataFrame([new_features])

    # Scale features
    input_scaled = scaler.transform(input_df)

    # Predict cluster
    cluster = model.predict(input_scaled)[0]

    # Get probabilities for each cluster
    probs = model.predict_proba(input_scaled)[0]

    # Get junction type
    junction_type = cluster_names.get(cluster, f"Cluster {cluster}")

    # Find similar junctions (based on Euclidean distance)
    distances = []
    for i, row in enumerate(features_scaled):
        dist = np.linalg.norm(input_scaled - row.reshape(1, -1))
        distances.append((junction_profiles.iloc[i]['junction_id'], dist))

    # Sort by distance (most similar first)
    similar_junctions = sorted(distances, key=lambda x: x[1])[:2]

    return {
        'cluster': int(cluster),
        'junction_type': junction_type,
        'confidence': float(probs[cluster]),
        'similar_junctions': similar_junctions
    }

