# Improved function to extract metadata from filepaths that works with your naming convention
def extract_metadata(filepath):
    # Look at the full path, not just the filename
    full_path = filepath.lower()
    base_name = os.path.basename(filepath).lower().replace('.csv', '')

    # For Amsterdam junction2's special weekday/weekend files
    if 'amsterdam2_weekday' in full_path or 'amsterdam2_weekend' in full_path:
        city = 'Amsterdam'
        junction_number = 2
    else:
        # More flexible pattern matching for various filename formats
        amsterdam_match = re.search(r'amsterdam[_\s]*(junction)?[_\s]*(\d)', full_path)
        dublin_match = re.search(r'dublin[_\s]*(junction)?[_\s]*(\d)', full_path)

        if amsterdam_match:
            city = 'Amsterdam'
            # The junction number might be in group 1 or 2 depending on the pattern
            junction_number = int(amsterdam_match.group(2) if amsterdam_match.group(2) else amsterdam_match.group(1))
        elif dublin_match:
            city = 'Dublin'
            # The junction number might be in group 1 or 2 depending on the pattern
            junction_number = int(dublin_match.group(2) if dublin_match.group(2) else dublin_match.group(1))
        else:
            city = None
            junction_number = None

    # Create a junction ID
    if city and junction_number is not None:
        junction_id = f"{city}{junction_number}"
    else:
        junction_id = None

    # Time period identification from filename or path
    if 'morning' in full_path:
        time_period = 'morning'
    elif 'night' in full_path or 'evening' in full_path:
        time_period = 'night'
    else:
        time_period = None

    # Day identification from filename or path - check for both specific days and weekday/weekend
    day_options = ['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday', 'weekday', 'weekend']
    day = next((d for d in day_options if d in full_path), None)

    return {
        'city': city,
        'junction_number': junction_number,
        'junction_id': junction_id,
        'day': day,
        'time_period': time_period,
        'filepath': full_path  # For debugging
    }

