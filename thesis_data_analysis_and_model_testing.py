def process_single_image(img_path, output_file, time_period, day_type):
    """Process a single image and create a dataset row."""

    if not os.path.exists(img_path):
        print(f"File not found: {img_path}")
        return None

    # Create dataframe to store result
    results_df = pd.DataFrame(columns=[
        'timestamp', 'frame', 'person', 'bicycle', 'car',
        'motorcycle', 'bus', 'truck', 'vehicles',
        'time_period', 'day_type'
    ])

    # Generate timestamp (simulated)
    timestamp = time.time()

    # Load image
    img = cv2.imread(img_path)

    # Optional: Enhance image if necessary (uncomment if needed)
    # For night images, you might want to enhance brightness
    if time_period == "night":
        img = cv2.convertScaleAbs(img, alpha=1.5, beta=20)

    # Run YOLO detection with lower confidence for better detection
    results = model(img, conf=0.25)

    # Initialize counts
    counts = {
        'person': 0,
        'bicycle': 0,
        'car': 0,
        'motorcycle': 0,
        'bus': 0,
        'truck': 0
    }

    # Process detections
    for r in results:
        boxes = r.boxes
        for box in boxes:
            # Get class name
            cls_id = int(box.cls.item())
            cls_name = model.names[cls_id]

            # Count objects of interest
            if cls_name in counts:
                counts[cls_name] += 1

    # Calculate vehicles (sum of all vehicle types)
    vehicle_count = counts['car'] + counts['motorcycle'] + counts['bus'] + counts['truck']

    # Create 10 rows of data with frame numbers (to match your example format)
    # This simulates having multiple frames from video
    for i in range(10):
        frame_num = i * 30  # 30 frames apart
        timestamp_offset = timestamp + (i * 3.0)  # 3 seconds apart

        new_row = {
            'timestamp': timestamp_offset,
            'frame': frame_num,
            'person': counts['person'],
            'bicycle': counts['bicycle'],
            'car': counts['car'],
            'motorcycle': counts['motorcycle'],
            'bus': counts['bus'],
            'truck': counts['truck'],
            'vehicles': vehicle_count,
            'time_period': time_period,
            'day_type': day_type
        }
        results_df = pd.concat([results_df, pd.DataFrame([new_row])], ignore_index=True)

    # Save annotated image for verification
    img_annotated = results[0].plot()
    output_image = f"processed_images/{day_type}_{time_period}.jpg"
    cv2.imwrite(output_image, img_annotated)

    print(f"Processed {img_path}: {counts}")

    # Save to CSV
    results_df.to_csv(output_file, index=False)
    print(f"Results saved to {output_file}")

    # Download the CSV file
    files.download(output_file)

    return results_df, counts

