# Function to load junction data
def load_junction_data(file_paths, problem_junction="Amsterdam2"):
    # Dictionary to store dataframes by junction
    junction_data = {}

    # Track the detected junctions
    detected_junctions = set()

    # First pass: identify all junctions
    for file_path in file_paths:
        metadata = extract_metadata(file_path)
        if metadata['junction_id']:
            detected_junctions.add(metadata['junction_id'])

    print(f"Detected junctions: {sorted(list(detected_junctions))}")
    print(f"Using '{problem_junction}' as the problematic junction")

    # Second pass: load the data
    for file_path in file_paths:
        metadata = extract_metadata(file_path)

        # Skip if we couldn't identify the junction
        if not metadata['junction_id']:
            print(f"Skipping {os.path.basename(file_path)} - could not identify junction")
            continue

        # Special handling for problematic junction
        if metadata['junction_id'] == problem_junction:
            # For the problem junction, only use weekday/weekend data
            if metadata['day'] in ['weekday', 'weekend']:
                pass  # Process this file
            else:
                print(f"Skipping non-weekday/weekend data for problem junction: {os.path.basename(file_path)}")
                continue

        # Read the file
        try:
            df = pd.read_csv(file_path)

            # Add metadata columns
            df['city'] = metadata['city']
            df['junction_number'] = metadata['junction_number']
            df['junction_id'] = metadata['junction_id']
            df['day'] = metadata['day']
            df['time_period'] = metadata['time_period']

            # Initialize or append to the junction's data
            if metadata['junction_id'] not in junction_data:
                junction_data[metadata['junction_id']] = df
            else:
                junction_data[metadata['junction_id']] = pd.concat([junction_data[metadata['junction_id']], df])

            print(f"Added {len(df)} rows from {os.path.basename(file_path)} for {metadata['junction_id']}")
        except Exception as e:
            print(f"Error reading {os.path.basename(file_path)}: {str(e)}")

    return junction_data

# Function to analyze junctions
def analyze_junctions(junction_data):
    # Create a dataframe for junction profiles
    profiles = []

    for junction_id, data in junction_data.items():
        print(f"Analyzing junction: {junction_id}")

        try:
            # Calculate basic statistics
            morning_stats = data[data['time_period'] == 'morning'].agg({
                'person': 'mean',
                'bicycle': 'mean',
                'car': 'mean',
                'motorcycle': 'mean',
                'bus': 'mean',
                'truck': 'mean',
                'vehicles': 'mean'
            })

            night_stats = data[data['time_period'] == 'night'].agg({
                'person': 'mean',
                'bicycle': 'mean',
                'car': 'mean',
                'motorcycle': 'mean',
                'bus': 'mean',
                'truck': 'mean',
                'vehicles': 'mean'
            })

            weekday_stats = data[data['day'].isin(['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'weekday'])].agg({
                'person': 'mean',
                'bicycle': 'mean',
                'car': 'mean',
                'motorcycle': 'mean',
                'bus': 'mean',
                'truck': 'mean',
                'vehicles': 'mean'
            })

            weekend_stats = data[data['day'].isin(['saturday', 'sunday', 'weekend'])].agg({
                'person': 'mean',
                'bicycle': 'mean',
                'car': 'mean',
                'motorcycle': 'mean',
                'bus': 'mean',
                'truck': 'mean',
                'vehicles': 'mean'
            })

            # Get city and junction number
            city = data['city'].iloc[0]
            junction_number = data['junction_number'].iloc[0]

            # Calculate key metrics (with 0.1 added to avoid division by zero)
            total_vehicles = data['vehicles'].mean()
            person_to_vehicle = data['person'].sum() / (data['vehicles'].sum() + 0.1)
            car_percentage = (data['car'].sum() / (data['vehicles'].sum() + 0.1)) * 100
            bicycle_percentage = (data['bicycle'].sum() / (data['vehicles'].sum() + 0.1)) * 100

            # Calculate ratios safely (handling empty data)
            if not morning_stats.empty and not night_stats.empty and night_stats['vehicles'] > 0:
                morning_to_night_ratio = morning_stats['vehicles'] / night_stats['vehicles']
            else:
                morning_to_night_ratio = np.nan

            if not weekday_stats.empty and not weekend_stats.empty and weekend_stats['vehicles'] > 0:
                weekday_to_weekend_ratio = weekday_stats['vehicles'] / weekend_stats['vehicles']
            else:
                weekday_to_weekend_ratio = np.nan

            # Create profile
            profile = {
                'junction_id': junction_id,
                'city': city,
                'junction_number': junction_number,
                'avg_vehicles': total_vehicles,
                'person_to_vehicle_ratio': person_to_vehicle,
                'car_percentage': car_percentage,
                'bicycle_percentage': bicycle_percentage,
                'morning_traffic': morning_stats['vehicles'] if not morning_stats.empty else np.nan,
                'night_traffic': night_stats['vehicles'] if not night_stats.empty else np.nan,
                'morning_to_night_ratio': morning_to_night_ratio,
                'weekday_traffic': weekday_stats['vehicles'] if not weekday_stats.empty else np.nan,
                'weekend_traffic': weekend_stats['vehicles'] if not weekend_stats.empty else np.nan,
                'weekday_to_weekend_ratio': weekday_to_weekend_ratio,
                'morning_people': morning_stats['person'] if not morning_stats.empty else np.nan,
                'night_people': night_stats['person'] if not night_stats.empty else np.nan,
                'morning_cars': morning_stats['car'] if not morning_stats.empty else np.nan,
                'night_cars': night_stats['car'] if not night_stats.empty else np.nan,
                'morning_bicycles': morning_stats['bicycle'] if not morning_stats.empty else np.nan,
                'night_bicycles': night_stats['bicycle'] if not night_stats.empty else np.nan
            }

            profiles.append(profile)

        except Exception as e:
            print(f"Error analyzing junction {junction_id}: {str(e)}")

    # Convert to dataframe
    junction_profiles = pd.DataFrame(profiles)

    return junction_profiles

