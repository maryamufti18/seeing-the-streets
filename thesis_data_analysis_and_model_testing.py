            if not ret:
                break

            # Process every 30th frame
            if frame_count % 30 == 0:
                # Run YOLO detection
                results = model(frame)

                # Count objects
                counts = {'person': 0, 'bicycle': 0, 'car': 0, 'motorcycle': 0, 'bus': 0, 'truck': 0}

